// internal/codegen/generate.go
package codegen

import (
	"fmt"
	"sort"
	"strings"
)

// importSet records which packages the emitted code actually needs.
// Each emitter feeds it at the exact point where it writes code that
// uses the package, so the decision to emit and the decision to import
// live together (see friction #4 in TaskForge's NOTES.md).
type importSet map[string]struct{}

func (s importSet) add(name string) {
	s[name] = struct{}{}
}

// sorted returns the import paths in alphabetical order, as gofmt would.
func (s importSet) sorted() []string {
	names := make([]string, 0, len(s))
	for name := range s {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func GenerateValidate(packageName string, structs []StructInfo) string {
	var funcs strings.Builder
	imps := importSet{}

	validatableStructs := computeValidatableStructs(structs)

	wrote := false

	for _, s := range structs {
		rules := fieldRules(s)
		nested := nestedValidatableFields(s, validatableStructs)

		if len(rules) == 0 && len(nested) == 0 {
			continue
		}

		wrote = true
		fmt.Fprintf(&funcs, "func (in %s) Validate() error {\n", s.Name)
		for _, fr := range rules {
			funcs.WriteString(generateFieldChecks(fr, imps))
		}
		for _, nf := range nested {
			funcs.WriteString(generateNestedCheck(nf))
		}
		funcs.WriteString("\treturn nil\n}\n\n")
	}

	if !wrote {
		return ""
	}

	var out strings.Builder
	out.WriteString("// Code generated by gofast. DO NOT EDIT.\n\n")
	out.WriteString("package " + packageName + "\n\n")

	if len(imps) > 0 {
		out.WriteString("import (\n")
		for _, name := range imps.sorted() {
			fmt.Fprintf(&out, "\t%q\n", name)
		}
		out.WriteString(")\n\n")
	}

	out.WriteString(funcs.String())

	return out.String()
}

func computeValidatableStructs(structs []StructInfo) map[string]bool {
	result := map[string]bool{}

	for _, s := range structs {
		if len(fieldRules(s)) > 0 {
			result[s.Name] = true
		}
	}

	for {
		changed := false

		for _, s := range structs {
			if result[s.Name] {
				continue
			}

			if len(nestedValidatableFields(s, result)) > 0 {
				result[s.Name] = true
				changed = true
			}
		}

		if !changed {
			break
		}
	}

	return result
}

type nestedField struct {
	FieldName string
	TypeName  string
	Kind      string
}

func nestedValidatableFields(s StructInfo, validatable map[string]bool) []nestedField {
	var result []nestedField

	for _, f := range s.Fields {
		switch {
		case strings.HasPrefix(f.Type, "*"):
			typeName := strings.TrimPrefix(f.Type, "*")
			if validatable[typeName] {
				result = append(result, nestedField{FieldName: f.Name, TypeName: typeName, Kind: "pointer"})
			}
		case strings.HasPrefix(f.Type, "[]"):
			typeName := strings.TrimPrefix(f.Type, "[]")
			if validatable[typeName] {
				result = append(result, nestedField{FieldName: f.Name, TypeName: typeName, Kind: "slice"})
			}
		case strings.HasPrefix(f.Type, "map["):
			closeIdx := strings.Index(f.Type, "]")
			if closeIdx == -1 {
				continue
			}
			valueType := f.Type[closeIdx+1:]
			if validatable[valueType] {
				result = append(result, nestedField{FieldName: f.Name, TypeName: valueType, Kind: "map"})
			}
		default:
			if validatable[f.Type] {
				result = append(result, nestedField{FieldName: f.Name, TypeName: f.Type, Kind: "struct"})
			}
		}
	}

	return result
}

func generateNestedCheck(nf nestedField) string {
	switch nf.Kind {
	case "pointer":
		return fmt.Sprintf(
			"\tif in.%s != nil {\n\t\tif err := in.%s.Validate(); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n",
			nf.FieldName, nf.FieldName,
		)
	case "slice":
		return fmt.Sprintf(
			"\tfor _, item := range in.%s {\n\t\tif err := item.Validate(); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n",
			nf.FieldName,
		)
	case "map":
		return fmt.Sprintf(
			"\tfor _, item := range in.%s {\n\t\tif err := item.Validate(); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n",
			nf.FieldName,
		)
	case "struct":
		return fmt.Sprintf(
			"\tif err := in.%s.Validate(); err != nil {\n\t\treturn err\n\t}\n",
			nf.FieldName,
		)
	default:
		return ""
	}
}

type fieldRule struct {
	FieldName string
	Rules     []string
}

func fieldRules(s StructInfo) []fieldRule {
	var result []fieldRule
	for _, f := range s.Fields {
		rules := extractValidateRules(f.Tag)
		if len(rules) == 0 {
			continue
		}
		result = append(result, fieldRule{FieldName: f.Name, Rules: rules})
	}
	return result
}

func generateFieldChecks(fr fieldRule, imps importSet) string {
	var out strings.Builder

	if len(fr.Rules) > 0 && fr.Rules[0] == "dive" {
		var checks strings.Builder
		for _, rule := range fr.Rules[1:] {
			checks.WriteString(generateDiveCheck(fr.FieldName, rule, imps))
		}
		// If no inner rule emitted code, the loop is not opened:
		// an empty `for idx, v := range x { }` does not compile in Go
		// (declared and not used).
		if checks.Len() == 0 {
			return ""
		}
		fmt.Fprintf(&out, "\tfor idx, v := range in.%s {\n", fr.FieldName)
		out.WriteString(checks.String())
		out.WriteString("\t}\n")
		return out.String()
	}

	if len(fr.Rules) > 0 && fr.Rules[0] == "dive_key" {
		var checks strings.Builder
		for _, rule := range fr.Rules[1:] {
			checks.WriteString(generateDiveKeyCheck(fr.FieldName, rule, imps))
		}
		if checks.Len() == 0 {
			return ""
		}
		fmt.Fprintf(&out, "\tfor k := range in.%s {\n", fr.FieldName)
		out.WriteString(checks.String())
		out.WriteString("\t}\n")
		return out.String()
	}

	for _, rule := range fr.Rules {
		switch {
		case rule == "required":
			imps.add("fmt")
			fmt.Fprintf(&out,
				"\tif in.%s == \"\" {\n\t\treturn fmt.Errorf(\"%s is required\")\n\t}\n",
				fr.FieldName, fr.FieldName,
			)
		case rule == "email":
			imps.add("fmt")
			imps.add("strings")
			fmt.Fprintf(&out,
				"\tif !strings.Contains(in.%s, \"@\") {\n\t\treturn fmt.Errorf(\"%s must be a valid email\")\n\t}\n",
				fr.FieldName, fr.FieldName,
			)
		case strings.HasPrefix(rule, "min="):
			imps.add("fmt")
			n := strings.TrimPrefix(rule, "min=")
			fmt.Fprintf(&out,
				"\tif len(in.%s) < %s {\n\t\treturn fmt.Errorf(\"%s must be at least %s characters\")\n\t}\n",
				fr.FieldName, n, fr.FieldName, n,
			)
		case strings.HasPrefix(rule, "max="):
			imps.add("fmt")
			n := strings.TrimPrefix(rule, "max=")
			fmt.Fprintf(&out,
				"\tif len(in.%s) > %s {\n\t\treturn fmt.Errorf(\"%s must be at most %s characters\")\n\t}\n",
				fr.FieldName, n, fr.FieldName, n,
			)
		}
	}

	return out.String()
}

func generateDiveCheck(fieldName, rule string, imps importSet) string {
	switch {
	case rule == "required":
		imps.add("fmt")
		return fmt.Sprintf(
			"\t\tif v == \"\" {\n\t\t\treturn fmt.Errorf(\"%s[%%d] is required\", idx)\n\t\t}\n",
			fieldName,
		)
	case strings.HasPrefix(rule, "min="):
		imps.add("fmt")
		n := strings.TrimPrefix(rule, "min=")
		return fmt.Sprintf(
			"\t\tif len(v) < %s {\n\t\t\treturn fmt.Errorf(\"%s[%%d] must be at least %s characters\", idx)\n\t\t}\n",
			n, fieldName, n,
		)
	case strings.HasPrefix(rule, "max="):
		imps.add("fmt")
		n := strings.TrimPrefix(rule, "max=")
		return fmt.Sprintf(
			"\t\tif len(v) > %s {\n\t\t\treturn fmt.Errorf(\"%s[%%d] must be at most %s characters\", idx)\n\t\t}\n",
			n, fieldName, n,
		)
	default:
		return ""
	}
}

func generateDiveKeyCheck(fieldName, rule string, imps importSet) string {
	switch {
	case rule == "required":
		imps.add("fmt")
		return fmt.Sprintf(
			"\t\tif k == \"\" {\n\t\t\treturn fmt.Errorf(\"%s has an empty key\")\n\t\t}\n",
			fieldName,
		)
	case strings.HasPrefix(rule, "min="):
		imps.add("fmt")
		n := strings.TrimPrefix(rule, "min=")
		return fmt.Sprintf(
			"\t\tif len(k) < %s {\n\t\t\treturn fmt.Errorf(\"%s key %%q must be at least %s characters\", k)\n\t\t}\n",
			n, fieldName, n,
		)
	case strings.HasPrefix(rule, "max="):
		imps.add("fmt")
		n := strings.TrimPrefix(rule, "max=")
		return fmt.Sprintf(
			"\t\tif len(k) > %s {\n\t\t\treturn fmt.Errorf(\"%s key %%q must be at most %s characters\", k)\n\t\t}\n",
			n, fieldName, n,
		)
	default:
		return ""
	}
}