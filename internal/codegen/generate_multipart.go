// internal/codegen/generate_multipart.go
package codegen

import (
	"fmt"
	"strings"
)

const uploadedFileType = "*gofast.UploadedFile"

// GenerateBindMultipart generates BindMultipart methods for every
// struct with at least one `form:"..."` tagged field. See ADR 0017
// — this mirrors GenerateBindPath/GenerateBindQuery exactly, using
// build-time codegen instead of runtime reflection.
func GenerateBindMultipart(packageName string, structs []StructInfo) string {
	var body strings.Builder

	body.WriteString("// Code generated by gofast. DO NOT EDIT.\n\n")
	body.WriteString("package " + packageName + "\n\n")

	needsGofastImport := false
	for _, s := range structs {
		for _, f := range tagFields(s, "form") {
			if f.FieldType == uploadedFileType {
				needsGofastImport = true
			}
		}
	}

	if needsGofastImport {
		body.WriteString("import (\n\t\"gofast/gofast\"\n\t\"mime/multipart\"\n)\n\n")
	} else {
		body.WriteString("import \"mime/multipart\"\n\n")
	}

	wrote := false

	for _, s := range structs {
		fields := tagFields(s, "form")
		if len(fields) == 0 {
			continue
		}

		wrote = true
		fmt.Fprintf(&body, "func (i *%s) BindMultipart(form *multipart.Form) error {\n", s.Name)
		for _, ff := range fields {
			body.WriteString(generateMultipartFieldAssign(ff))
		}
		body.WriteString("\treturn nil\n")
		body.WriteString("}\n\n")
	}

	if !wrote {
		return ""
	}

	return body.String()
}

func generateMultipartFieldAssign(ff taggedField) string {
	var out strings.Builder

	switch ff.FieldType {
	case uploadedFileType:
		fmt.Fprintf(&out, "\tif files, ok := form.File[%q]; ok && len(files) > 0 {\n", ff.ParamName)
		fmt.Fprintf(&out, "\t\ti.%s = gofast.NewUploadedFile(files[0])\n", ff.FieldName)
		out.WriteString("\t}\n")
	case "string":
		fmt.Fprintf(&out, "\tif vals, ok := form.Value[%q]; ok && len(vals) > 0 {\n", ff.ParamName)
		fmt.Fprintf(&out, "\t\ti.%s = vals[0]\n", ff.FieldName)
		out.WriteString("\t}\n")
	default:
		fmt.Fprintf(&out, "\t// unsupported type %q for field %s, skipped\n", ff.FieldType, ff.FieldName)
	}

	return out.String()
}